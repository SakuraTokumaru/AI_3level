/** レベルから、実際に使うシステムプロンプトを組み立てる */
export function resolvePrompt(level) {
  const prompt = PROMPTS[level];
  if (!prompt) return null;
  return COMMON_RULES + '\n\n' + 'あなたの名前は「' + NAMES[level] + '」です。\n\n' + prompt;
}
